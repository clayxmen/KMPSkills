import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const curriculumDir = path.resolve(__dirname, '../../../curriculum');
const outputFile = path.resolve(__dirname, '../src/engine/curriculum-data.ts');

console.log(`Scanning curriculum from: ${curriculumDir}`);

const files = fs.readdirSync(curriculumDir)
  .filter(f => f.endsWith('.md'))
  .sort();

console.log(`Found ${files.length} curriculum files.`);

const levels = [];
let readmeContent = '';

for (const file of files) {
  const filePath = path.join(curriculumDir, file);
  const rawContent = fs.readFileSync(filePath, 'utf-8');

  if (file === 'README.md') {
    readmeContent = rawContent;
    continue;
  }

  const levelMatch = file.match(/^(\d+)-level-(\d+)-(.+)\.md$/);
  const levelNum = levelMatch ? parseInt(levelMatch[2], 10) : 0;
  const slug = file.replace(/\.md$/, '');

  // Extract main title
  const titleMatch = rawContent.match(/^#\s+(.+)$/m);
  const title = titleMatch ? titleMatch[1].trim() : file;

  // Extract sections (## ...)
  const sectionMatches = [...rawContent.matchAll(/^##\s+([^\n]+)$/gm)];
  const sections = sectionMatches.map(m => m[1].trim());

  // Extract objective summary (under ## 🎯 Mục Tiêu Học Tập or first paragraph)
  let description = '';
  const objMatch = rawContent.match(/## 🎯 Mục Tiêu Học Tập\s*\n([\s\S]*?)(?=\n## |\n---)/);
  if (objMatch) {
    description = objMatch[1]
      .split('\n')
      .map(l => l.replace(/^\d+\.\s*/, '').trim())
      .filter(Boolean)
      .slice(0, 3)
      .join('; ');
  } else {
    description = `Masterclass curriculum Level ${levelNum}: ${title}`;
  }

  levels.push({
    level: levelNum,
    slug,
    filename: file,
    title,
    description,
    sections,
    content: rawContent
  });
}

// Sort by level ascending
levels.sort((a, b) => a.level - b.level);

const fileHeader = `// AUTO-GENERATED BY scripts/generate-curriculum-data.mjs
// DO NOT EDIT MANUALLY. CONTAINS EMBEDDED KMP CURRICULUM REPOSITORY.

export interface CurriculumSection {
  title: string;
}

export interface CurriculumLevel {
  level: number;
  slug: string;
  filename: string;
  title: string;
  description: string;
  sections: string[];
  content: string;
}

export const EMBEDDED_CURRICULUM: CurriculumLevel[] = ${JSON.stringify(levels, null, 2)};

export const CURRICULUM_README: string = ${JSON.stringify(readmeContent)};
`;

fs.writeFileSync(outputFile, fileHeader, 'utf-8');
console.log(`Generated ${outputFile} with ${levels.length} curriculum levels successfully!`);
